#!/bin/sh
# Regenerates docs/REQ-INDEX.md: section -> line range for the big docs, so a task
# reads one section (Read offset/limit) instead of the whole file. Run after editing them.
cd "$(dirname "$0")/.." || exit 1
out=docs/REQ-INDEX.md
{
  echo "# Requirement index"
  echo
  echo "Generated by \`scripts/req-index.sh\`; rerun after editing a doc below. Read a section with"
  echo "\`Read\` \`offset\`/\`limit\`, not the whole file."
  for f in REQ_V2.MD REQ_V3.MD docs/DESIGN.md; do
    echo
    echo "## $f ($(wc -l < "$f" | tr -d ' ') lines)"
    echo
    echo "| Lines | Section |"
    echo "|---|---|"
    awk -v total="$(wc -l < "$f")" '
      /^## / { if (name) print "| " start "-" NR-1 " | " name " |"; name=substr($0,4); start=NR }
      END { if (name) print "| " start "-" total " | " name " |" }' "$f"
  done
} > "$out"
